"""Copies contract ABIs and the Platform bytecode from Foundry's build output into docs/contracts.js (the website)."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
NAMES = ["Platform", "ExposureOracle", "MockExchange", "MockToken", "FundFactory", "ThemeFund"]

out = {}
for name in NAMES:
    art = json.loads((ROOT / "out" / f"{name}.sol" / f"{name}.json").read_text())
    out[name] = {"abi": art["abi"]}
art = json.loads((ROOT / "out" / "Platform.sol" / "Platform.json").read_text())
out["Platform"]["bytecode"] = art["bytecode"]["object"]

js = "// Generated by script/export_abis.py. Do not edit by hand.\nwindow.CONTRACTS = " + json.dumps(out) + ";\n"
(ROOT.parent.parent / "docs" / "contracts.js").write_text(js)
print(f"wrote docs/contracts.js ({len(js) // 1024} KB)")
